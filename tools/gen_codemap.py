"""Regenerates docs/CODE_MAP.md (file -> members). Run from the project root:  python tools/gen_codemap.py"""
import glob, os, re
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out = ['# CODE MAP', '', 'Generated by `tools/gen_codemap.py` - regenerate after structural changes.', '']
DECL = re.compile(r'^ {8}(?:(?:public|private|protected|internal|static|override|virtual|sealed)\s+)*[\w<>\[\],\.\? ]+?\s+(\w+)\s*\(([^;{}]*)\)\s*$')
TYPE = re.compile(r'^ {4}(?:static |partial |sealed )*(class|enum|delegate)\s+(\w+)')
for f in sorted(glob.glob(os.path.join(ROOT, 'src', '**', '*.cs'), recursive=True)):
    rel = os.path.relpath(f, ROOT).replace('\\', '/')
    lines = open(f, encoding='utf-8-sig').read().split('\n')
    first = lines[0].lstrip('/ ').strip()
    out += ['## `%s`' % rel, '', '_%s_' % first, '']
    for i, l in enumerate(lines, 1):
        l = l.rstrip('\r')
        t = TYPE.match(l)
        if t: out.append('- **%s %s** (L%d)' % (t.group(1), t.group(2), i)); continue
        m = DECL.match(l)
        if m and m.group(1) not in ('if', 'for', 'foreach', 'while', 'switch', 'using', 'lock', 'catch'):
            out.append('  - `%s(%s)` L%d' % (m.group(1), re.sub(r'\s+', ' ', m.group(2)).strip()[:60], i))
    out.append('')
os.makedirs(os.path.join(ROOT, 'docs'), exist_ok=True)
open(os.path.join(ROOT, 'docs', 'CODE_MAP.md'), 'w', encoding='utf-8', newline='\n').write('\n'.join(out))
print('docs/CODE_MAP.md written')
